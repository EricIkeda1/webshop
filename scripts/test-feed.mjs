import { build } from 'esbuild';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const temp = await mkdtemp(join(tmpdir(), 'eyi-feed-'));
const originalFetch = globalThis.fetch;
const items = Array.from({length: 37}, (_, index) => ({ id: index + 1, title: `Product ${index + 1}`, description: 'Test product', brand: 'EYI', category: index % 3 === 0 ? 'beauty' : index % 3 === 1 ? 'fragrances' : 'skin-care', price: 10 + index * 5, rating: 3 + index % 3 * .5, discountPercentage: 35 - index / 2, stock: 20, images: [], reviews: [], thumbnail: '' }));
let calls = [];
let failNext = false;
let abortedRequest = false;
globalThis.fetch = async (url, options) => {
  options?.signal?.throwIfAborted();
  if (abortedRequest) throw new DOMException('Aborted', 'AbortError');
  if (failNext) throw new Error('Temporary failure');
  const u = new URL(String(url), 'http://localhost');
  if (u.pathname === '/assets/products.json') throw new Error('Fallback unavailable for this test');
  calls.push(u);
  let products = [...items];
  if (u.pathname.includes('/category/')) products = products.filter(item => item.category === decodeURIComponent(u.pathname.split('/').at(-1)));
  if (u.searchParams.has('q')) products = products.filter(item => item.title.toLowerCase().includes(u.searchParams.get('q').toLowerCase()));
  const key = u.searchParams.get('sortBy'); const direction = u.searchParams.get('order') === 'asc' ? 1 : -1;
  products.sort((a, b) => direction * (a[key] - b[key]));
  const total = products.length; const skip = Number(u.searchParams.get('skip')); const limit = Number(u.searchParams.get('limit'));
  assert(limit > 0 && limit <= 12, 'Requests must be bounded to at most 12 items');
  return Response.json({ products: products.slice(skip, skip + limit), total, skip, limit });
};
try {
  const output = join(temp, 'feed.mjs');
  await build({ entryPoints: ['src/services/productFeed.ts'], outfile: output, bundle: true, platform: 'node', format: 'esm', logLevel: 'silent' });
  const { createProductFeed } = await import(pathToFileURL(output).href);
  const defaultFeed = createProductFeed({});
  const first = await defaultFeed.next();
  assert.equal(first.products.length, 12); assert.equal(calls.length, 1); assert.equal(calls[0].searchParams.get('skip'), '0'); assert(first.hasMore);
  const second = await defaultFeed.next();
  assert.equal(second.products.length, 12); assert.equal(calls[1].searchParams.get('skip'), '12');
  assert.equal(new Set([...first.products, ...second.products].map(item => item.id)).size, 24);
  const third = await defaultFeed.next(); const last = await defaultFeed.next();
  assert.equal(third.products.length, 12); assert.equal(last.products.length, 1); assert.equal(last.hasMore, false);
  console.log('PASS: 12 initial products, next page on request, no duplicates, final partial page.');
  for (const sort of ['low', 'high', 'rating']) {
    const feed = createProductFeed({ category: 'Beleza', sort });
    const accumulated = [];
    let page;
    do { page = await feed.next(); accumulated.push(...page.products); } while (page.hasMore);
    const key = sort === 'rating' ? 'rating' : 'price';
    const direction = sort === 'low' ? 1 : -1;
    assert.equal(accumulated.length, items.length);
    for (let i = 1; i < accumulated.length; i++) assert(direction * (accumulated[i][key] - accumulated[i - 1][key]) >= 0);
  }
  console.log('PASS: grouped category pagination preserves global price/rating sorting.');
  const filtered = createProductFeed({ category: 'Beleza', rating: 4, maxPrice: 120, offers: true, query: 'Product' });
  const filteredProducts = [];
  let result;
  do { result = await filtered.next(); filteredProducts.push(...result.products); } while (result.hasMore);
  assert.deepEqual(filteredProducts.map(item => item.id).sort((a,b) => a-b), items.filter(item => item.rating >= 4 && item.price <= 120 && item.discountPercentage >= 15).map(item => item.id));
  console.log('PASS: filters apply to the full paginated selection.');
  const retryFeed = createProductFeed({ category: 'Beleza' });
  failNext = true;
  await assert.rejects(retryFeed.next());
  failNext = false;
  const retried = await retryFeed.next();
  assert.equal(retried.products.length, 12);
  assert.equal(retried.products[0].id, 1);
  console.log('PASS: failed request can be retried without skipping products.');
  const controller = new AbortController(); controller.abort();
  abortedRequest = true;
  await assert.rejects(createProductFeed({}).next(controller.signal));
  console.log('PASS: cancellation does not fall back to a full catalog request.');
} finally { globalThis.fetch = originalFetch; await rm(temp, { recursive: true, force: true }); }
